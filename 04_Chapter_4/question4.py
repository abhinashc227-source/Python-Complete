# Write a program to sum a list with 4 numbers. 

number = []

n1 = int(input("Enter the number 1 : "))
number.append(n1)

n2 = int(input("Enter the number 2 : "))
number.append(n2)

n3 = int(input("Enter the number 3 : "))
number.append(n3)

n4 = int(input("Enter the number 4 : "))
number.append(n4)

sum = n1+n2+n3+n4

print("List : ",number)
print("Sum : ",sum)